/** Strip admin suffixes so "郑州市"→"郑州", "河南省"→"河南", "广西壮族自治区"→"广西". */
function stripSuffix(name) {
  if (!name) return '';
  return String(name)
    .replace(/维吾尔|壮族|回族/g, '')
    .replace(/自治区|特别行政区|省|市|地区|盟/g, '')
    .trim();
}

/** Neighboring prefecture-level cities of `city` within `province` (bare names). */
function neighborCitiesFor(province, city) {
  const p = stripSuffix(province);
  const c = stripSuffix(city);
  const all = PROVINCE_CITIES[p] || [];
  return all.filter((x) => x !== c);
}

/** Provinces adjacent to `province` (bare names). */
function neighborProvincesFor(province) {
  return PROVINCE_NEIGHBORS[stripSuffix(province)] || [];
}

/** Full prefecture-city list of `province` (bare names). */
function citiesOfProvince(province) {
  return PROVINCE_CITIES[stripSuffix(province)] || [];
}

